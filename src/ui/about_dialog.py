# Значения, которых нет в APP_DEFAULTS (они не сохраняются или доступны только
# для чтения), чтобы строка «по умолчанию» не была пустой.
HELP_EXTRA_DEFAULTS: dict[str, str] = {
    "bg/prompt": "не сохраняется",
    "ui/language": "Русский",
    "ui/log_level": "INFO",
    "paths/data": "data\\",
    "paths/models": "models\\",
    "paths/cache": "%USERPROFILE%\\.rembg\\models",
}


def _default_text(key: str) -> str:
    """Человекочитаемое значение по умолчанию для строки справки."""
    if key not in APP_DEFAULTS:
        return HELP_EXTRA_DEFAULTS.get(key, "—")
    value = APP_DEFAULTS[key]
    if key == "upscale/factor":
        return f"×{value}"
    if isinstance(value, bool):
        return "вкл." if value else "выкл."
    return str(value)


def _render_help() -> str:
    """Собрать HTML справки из HELP_GROUPS и актуальных предустановок."""
    parts = [HELP_INTRO]
    for tab_title, sections in HELP_GROUPS:
        parts.append(f"<h3>{tab_title}</h3>")
        for section_title, settings in sections:
            if section_title:
                parts.append(f"<h4>{section_title}</h4>")
            for key, label, description in settings:
                parts.append(
                    f"<p><b>{label}</b> <small>[{key}] · по умолчанию: "
                    f"{_default_text(key)}</small><br>{description}</p>"
                )
    parts.append(
        "<p><b>Кнопки внизу окна «Настройки».</b> «OK» сохраняет изменения, "
        "«Отмена» — отбрасывает. Кнопка «Сбросить настройки» на вкладке «Общие» "
        "возвращает проверенные значения: имейте в виду, что она сбрасывает и "
        "ваши собственные пороги вырезки.</p>"
    )
    return "".join(parts)


def _section(title: str, body: str, name: str) -> QLabel:
    label = QLabel(f"<h3>{title}</h3>{body}")
    label.setObjectName(name)
    label.setTextFormat(Qt.TextFormat.RichText)
    label.setWordWrap(True)
    label.setTextInteractionFlags(Qt.TextInteractionFlag.TextSelectableByMouse)
    return label


class AboutDialog(QDialog):
    """Окно с описанием приложения и подробной помощью по настройкам."""

    def __init__(self, parent: QWidget | None = None, dark: bool | None = None) -> None:
        super().__init__(parent)
        self._dark_titlebar = theme_is_dark(parent) if dark is None else dark
        self.setWindowTitle("О программе")
        self.setMinimumSize(560, 520)

        layout = QVBoxLayout(self)
        tabs = QTabWidget()

        # ----- вкладка «О приложении» (прежнее содержимое) -----
        scroll = QScrollArea()
        scroll.setWidgetResizable(True)
        scroll.setFrameShape(QFrame.Shape.NoFrame)
        # Без собственного objectName вьюпорт рисуется системным светлым цветом,
        # и в тёмной теме светлый текст становится нечитаемым.
        scroll.viewport().setObjectName("aboutViewport")
        content = QWidget()
        content.setObjectName("aboutContent")
        inner = QVBoxLayout(content)
        inner.setContentsMargins(16, 12, 16, 12)
        inner.setSpacing(12)

        title = QLabel(f"<h2>{APP_TITLE}</h2>")
        title.setObjectName("aboutTitle")
        title.setTextFormat(Qt.TextFormat.RichText)
        title.setTextInteractionFlags(Qt.TextInteractionFlag.TextSelectableByMouse)
        inner.addWidget(title)
        inner.addWidget(_section("Для чего это нужно", PURPOSE, "aboutPurpose"))
        inner.addWidget(_section("Как пользоваться", STEPS, "aboutSteps"))
        inner.addWidget(_section("Какие инструменты работают внутри", TOOLS, "aboutTools"))
        inner.addWidget(_section("О размере фона", RESOLUTION, "aboutResolution"))
        inner.addWidget(_section("О приватности", PRIVACY, "aboutPrivacy"))
        inner.addWidget(_section("Похожие продукты и преимущества", MARKET, "aboutMarket"))
        scroll.setWidget(content)
        tabs.addTab(scroll, "О приложении")

        # ----- вкладка «Помощь» -----
        help_scroll = QScrollArea()
        help_scroll.setWidgetResizable(True)
        help_scroll.setFrameShape(QFrame.Shape.NoFrame)
        help_scroll.viewport().setObjectName("helpViewport")
        help_content = QWidget()
        help_content.setObjectName("helpContent")
        help_inner = QVBoxLayout(help_content)
        help_inner.setContentsMargins(16, 12, 16, 12)
        help_label = QLabel(_render_help())
        help_label.setObjectName("helpText")
        help_label.setTextFormat(Qt.TextFormat.RichText)
        help_label.setWordWrap(True)
        help_label.setTextInteractionFlags(Qt.TextInteractionFlag.TextSelectableByMouse)
        help_inner.addWidget(help_label)
        help_scroll.setWidget(help_content)
        tabs.addTab(help_scroll, "Помощь")

        layout.addWidget(tabs)

        buttons = QDialogButtonBox(QDialogButtonBox.StandardButton.Close)
        buttons.button(QDialogButtonBox.StandardButton.Close).clicked.connect(self.reject)
        layout.addWidget(buttons)

    def showEvent(self, event) -> None:
        super().showEvent(event)
        # HWND уже создан — красим системную шапку в точный цвет фона темы.
        theme = "Тёмная" if self._dark_titlebar else "Светлая"
        apply_dark_titlebar(self, self._dark_titlebar, THEME_WINDOW_COLORS[theme])
